CREATE TABLE IF NOT EXISTS hp_medical_insurance_refunds (
	refund_id VARCHAR(64) NOT NULL,
	medical_order_id VARCHAR(64) NOT NULL,
	owner_user_id VARCHAR(64) NOT NULL,
	pay_ord_id VARCHAR(64) NOT NULL,
	refund_no VARCHAR(64) NOT NULL,
	idempotency_key VARCHAR(128) NOT NULL,
	refund_type VARCHAR(8) NOT NULL,
	total_fen BIGINT UNSIGNED NOT NULL,
	cash_fen BIGINT UNSIGNED NOT NULL,
	personal_account_fen BIGINT UNSIGNED NOT NULL,
	fund_fen BIGINT UNSIGNED NOT NULL,
	medical_status VARCHAR(16) NOT NULL,
	medical_ref_status VARCHAR(8) NULL,
	medical_provider_request_id VARCHAR(128) NULL,
	wechat_status VARCHAR(16) NOT NULL,
	wechat_merchant_refund_no VARCHAR(64) NULL,
	status VARCHAR(16) NOT NULL,
	last_error_code VARCHAR(128) NULL,
	version INT UNSIGNED NOT NULL,
	created_at DATETIME(3) NOT NULL,
	updated_at DATETIME(3) NOT NULL,
	PRIMARY KEY (refund_id),
	UNIQUE KEY uq_hp_medical_insurance_refunds_refund_no (refund_no),
	UNIQUE KEY uq_hp_medical_insurance_refunds_idempotency (medical_order_id, idempotency_key),
	KEY idx_hp_medical_insurance_refunds_order (medical_order_id, updated_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
